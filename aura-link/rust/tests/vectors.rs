//! Shared test vectors: ../test-vectors/aura-link-v1.txt is checked byte for byte here and by the
//! Kotlin tests (aura-link/kotlin, run inside the phone and watch builds). Regenerate (only when
//! the protocol changes on purpose): `AURA_WRITE_VECTORS=1 cargo test --test vectors`.

use aura_link::aead::Sealer;
use aura_link::fast::fast_keys;
use aura_link::file::FileOffer;
use aura_link::handshake::{hmac, psk_from_k0, psk_proof, role, schedule, transcript, watch_auth_message, Ephemeral, Hello, AUTH_PSK};
use aura_link::msg::{FastOffer, MediaState, Message};
use aura_link::wire::R_AUTH;
use p256::ecdsa::signature::Signer;
use p256::ecdsa::SigningKey;
use p256::pkcs8::EncodePublicKey;

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../test-vectors/aura-link-v1.txt");

fn generate() -> String {
    let mut out = String::from("# Aura Link v1 shared test vectors (generated by aura-link/rust/tests/vectors.rs; hex unless noted)\n");
    let mut put = |k: &str, v: &[u8]| out.push_str(&format!("{k}={}\n", hex::encode(v)));
    let secret = b"0123456789abcdefghij";
    let k0 = hmac(secret, &[b"continuity-unlock/v2/key/0"]);
    let pc_id: [u8; 8] = hmac(secret, &[b"continuity-unlock/v2/id"])[..8].try_into().unwrap();
    let psk = psk_from_k0(&k0);
    put("secret_ascii_hex", secret);
    put("k0", &k0);
    put("pc_id", &pc_id);
    put("psk", &psk);

    // phone <-> PC session, PC initiates
    let ei = Ephemeral::from_scalar(&[0x11; 32]).unwrap();
    let er = Ephemeral::from_scalar(&[0x22; 32]).unwrap();
    put("eph_i_scalar", &[0x11; 32]);
    put("eph_r_scalar", &[0x22; 32]);
    put("eph_i_pub", &ei.public());
    put("eph_r_pub", &er.public());
    let hi = Hello { ver_min: 1, ver_max: 1, role: role::PC, pc_id, nonce: [0x33; 32], eph: ei.public(), caps: 0x0d, name: "PC".into() }.encode();
    let hr = Hello { ver_min: 1, ver_max: 1, role: role::PHONE, pc_id, nonce: [0x44; 32], eph: er.public(), caps: 0x03, name: "Phone".into() }.encode();
    put("hello_i", &hi);
    put("hello_r", &hr);
    let th = transcript(&hi, &hr);
    let z = ei.agree(&er.public()).unwrap();
    assert_eq!(z, er.agree(&ei.public()).unwrap());
    let k = schedule(&psk, &z, &th);
    put("th", &th);
    put("z", &z);
    put("k_auth", &k.auth);
    put("k_i2r", &k.i2r);
    put("k_r2i", &k.r2i);
    put("k_fast", &k.fast);
    put("auth_i", &[&[R_AUTH, AUTH_PSK][..], &psk_proof(&k.auth, role::PC)].concat());
    put("auth_r", &[&[R_AUTH, AUTH_PSK][..], &psk_proof(&k.auth, role::PHONE)].concat());
    let mut m = Message::text("hello aura");
    m.id = 1;
    put("msg1_plain", &m.encode());
    let mut s = Sealer::new(&k.i2r);
    put("msg1_record", &s.seal(&m.encode()));
    let mut m2 = Message::url("https://youtu.be/dQw4w9WgXcQ", Some(42_000));
    m2.id = 2;
    put("msg2_plain", &m2.encode());
    put("msg2_record", &s.seal(&m2.encode()));
    let mut a = Message::ack(1);
    a.id = 0x01020304;
    put("ack_plain", &a.encode());
    put("ack_record", &Sealer::new(&k.r2i).seal(&a.encode()));
    let (c2s, s2c) = fast_keys(&k.fast, &[0x55; 16]);
    put("fast_ticket", &[0x55; 16]);
    put("fast_c2s", &c2s);
    put("fast_s2c", &s2c);
    put("fast_offer", &FastOffer { port: 47900, ticket: [0x55; 16], addrs: vec!["192.168.1.115".parse().unwrap()] }.encode());
    put("file_offer", &FileOffer { id: [0x66; 16], size: 5_242_880, sha256: [0x77; 32], name: "photo.jpg".into(), mime: "image/jpeg".into() }.encode());
    let mut r = Message::ring(true);
    r.id = 7;
    put("ring_on_plain", &r.encode());
    let mut mc = Message::media_cmd(aura_link::msg::media_cmd::NEXT);
    mc.id = 8;
    put("media_cmd_plain", &mc.encode());
    let mut pr = Message::present(aura_link::msg::present_cmd::BLACK);
    pr.id = 9;
    put("present_plain", &pr.encode());
    let mut art = Message::media_art(&[0xff, 0xd8, 0xff, 0xd9]);
    art.id = 10;
    put("media_art_plain", &art.encode());
    put("media_state", &MediaState { playing: true, position_ms: 61_000, duration_ms: 200_000, title: "Song".into(), artist: "Artist".into(), volume: None }.encode());
    put("media_state_vol", &MediaState { playing: false, position_ms: 1, duration_ms: 2, title: "T".into(), artist: "A".into(), volume: Some((42, true)) }.encode());

    // watch -> PC session (zero salt, ECDSA auth)
    let sk = SigningKey::from_slice(&[0x07; 32]).unwrap();
    put("watch_key_scalar", &[0x07; 32]);
    put("watch_pub_der", p256::PublicKey::from(*sk.verifying_key()).to_public_key_der().unwrap().as_bytes());
    let hw = Hello { ver_min: 1, ver_max: 1, role: role::WATCH, pc_id, nonce: [0x88; 32], eph: ei.public(), caps: 0x40, name: "Watch".into() }.encode();
    let hp = Hello { ver_min: 1, ver_max: 1, role: role::PC, pc_id, nonce: [0x99; 32], eph: er.public(), caps: 0x18, name: "PC".into() }.encode();
    put("w_hello_i", &hw);
    put("w_hello_r", &hp);
    let thw = transcript(&hw, &hp);
    let kw = schedule(&[0u8; 32], &z, &thw);
    put("w_th", &thw);
    put("w_k_i2r", &kw.i2r);
    put("w_k_r2i", &kw.r2i);
    put("w_auth_msg", &watch_auth_message(&thw));
    let sig: p256::ecdsa::Signature = sk.sign(&watch_auth_message(&thw)); // RFC 6979: deterministic
    put("w_auth_sig_der", sig.to_der().as_bytes());

    // item 17: the phone's fingerprint-signed remote unlock frame (key = level-3 pairing key)
    let k3 = hmac(secret, &[b"continuity-unlock/v2/key/3"]);
    put("k3", &k3);
    put("cupu_frame", &aura_link::remote::unlock_frame(&k3, &[0x5a; 16], 1_700_000_000_123, &pc_id));
    put("tailnet_msg", &Message::json(aura_link::msg::kind::TAILNET, r#"{"ip":"100.101.102.103","port":47140}"#).encode());
    out
}

#[test]
fn shared_vectors_are_current() {
    let want = generate();
    if std::env::var("AURA_WRITE_VECTORS").is_ok() {
        std::fs::write(PATH, &want).unwrap();
    }
    let have = std::fs::read_to_string(PATH).expect("vector file (AURA_WRITE_VECTORS=1 to create)").replace("\r\n", "\n");
    assert_eq!(have, want, "protocol output changed: update the Kotlin side too");
}

#[test]
fn k0_and_pc_id_match_the_unlock_stack_known_vector() {
    // same derivation as unlock-pc protocol::derive (its own test pins the level-1 MAC)
    let secret = b"0123456789abcdefghij";
    let pc_id = &hmac(secret, &[b"continuity-unlock/v2/id"])[..8];
    let file = include_str!("../../../unlock-watch/shared/test-vectors/pc-event-v2.txt");
    let want = file.lines().find_map(|l| l.strip_prefix("pc_id=")).unwrap().trim();
    let key0 = file.lines().find_map(|l| l.strip_prefix("key0=")).unwrap().trim();
    assert_eq!(hex::encode(pc_id), want);
    assert_eq!(hex::encode(hmac(secret, &[b"continuity-unlock/v2/key/0"])), key0);
}
